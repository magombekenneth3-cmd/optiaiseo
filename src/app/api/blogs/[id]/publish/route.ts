interface AiCheckResult {
    isAi: boolean;
    aiProbabilityScore: number;
}

async function detectAiContent(content: string): Promise<AiCheckResult> {
    try {
        const prompt = `Analyze the following blog content and determine the probability (0-100) that it was generated by an AI assistant without human editing. Highly repetitive phrasing, lack of transition variation, and generic list layouts are indicators of pure AI content.

Return JSON of shape:
{
  "isAi": boolean,
  "aiProbabilityScore": number
}

Content to analyze:
${content.substring(0, 3000)}`;

        return await generateWithFallbackJson<AiCheckResult>({
            prompt,
            systemPrompt: "You are an expert editor and AI content detector.",
            validate: (json: any) => {
                if (typeof json?.isAi !== "boolean" || typeof json?.aiProbabilityScore !== "number") {
                    throw new Error("Invalid format");
                }
                return json as AiCheckResult;
            }
        });
    } catch {
        return { isAi: false, aiProbabilityScore: 0 };
    }
}
async function checkOriginality(text: string): Promise<{ isOriginal: boolean, conflictingUrls: string[] }> {
    if (!process.env.SERPER_API_KEY) return { isOriginal: true, conflictingUrls: [] };
    const plainText = text
        .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '')
        .replace(/<[^>]+>/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
    const sentences = plainText.match(/[^.!?]+[.!?]+/g) || [plainText];
    const sample = sentences.sort((a, b) => b.length - a.length).slice(0, 3).join(' ');

    try {
        const res = await fetch('https://google.serper.dev/search', {
            method: 'POST',
            headers: { 'X-API-KEY': process.env.SERPER_API_KEY, 'Content-Type': 'application/json' },
            body: JSON.stringify({ q: `"${sample.trim()}"`, num: 3 }),
            signal: AbortSignal.timeout(6000)
        });
        const data = await res.json();

        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        const dupes = data.organic?.filter((r: any) => r.snippet?.includes(sample.trim().substring(0, 40))) || [];
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        return { isOriginal: dupes.length === 0, conflictingUrls: dupes.map((d: any) => d.link) };
    } catch {
        return { isOriginal: true, conflictingUrls: [] };
    }
}

import { prisma } from "@/lib/prisma";
